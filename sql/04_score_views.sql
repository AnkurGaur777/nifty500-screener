create or replace view screener_master as
select
    c.company_id,
    c.symbol,
    c.name,
    c.isin,
    c.sector,
    c.industry,
    sc.peer_group,
    sc.scoring_date,
    sc.is_eligible,
    sc.data_completeness_pct,
    sc.total_score,
    sc.overall_rank,
    sc.sector_rank,
    sc.quality_score,
    sc.growth_score,
    sc.value_score,
    sc.safety_score,
    sc.red_flag_count,
    sc.red_flag_list,
    rf.flag_profit_up_cfo_down_2yr,
    rf.flag_low_cash_conversion,
    rf.flag_receivables_ballooning,
    rf.flag_debt_spike,
    rf.flag_weak_interest_coverage,
    rf.flag_persistent_negative_fcf,
    rf.flag_margin_erosion,
    rf.flag_high_other_income,
    ml.latest_fiscal_year,
    ml.market_cap_cr,
    ml.latest_close_price,
    ml.years_available,
    ml.roe,
    ml.roce,
    ml.operating_margin,
    ml.net_margin,
    ml.debt_to_equity,
    ml.interest_coverage,
    ml.net_debt_to_ebitda,
    ml.cfo_to_net_profit,
    ml.fcf_cr,
    ml.fcf_margin,
    ml.receivable_days,
    ml.inventory_days,
    ml.asset_turnover,
    ml.eps_growth_yoy,
    ml.revenue_cagr_3yr,
    ml.profit_cagr_3yr,
    ml.avg_roce_3yr,
    ml.avg_roe_3yr,
    ml.operating_margin_std_3yr,
    ml.pe_ratio,
    ml.pb_ratio,
    ml.ev_to_ebitda,
    ml.earnings_yield,
    ml.fcf_yield,
    ml.piotroski_f_score
from dim_company c
left join scores sc on c.company_id = sc.company_id
left join metrics_latest ml on c.company_id = ml.company_id
left join red_flags_detail rf on c.company_id = rf.company_id
where c.is_financial = false;
